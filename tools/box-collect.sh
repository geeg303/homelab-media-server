#!/usr/bin/env bash
# Runs ON the box as root (piped over ssh by tools/sync-from-box.sh).
# Copies a WHITELIST of config/scripts into a staging dir, redacts secrets, then checks that no known
# secret VALUE appears anywhere in the staged files. Prints only file names / counts, never values.
# On success writes the tarball to stdout's sibling file /root/reposync.tgz (mode 600).
set -euo pipefail
S=$(mktemp -d /root/reposync.XXXX); trap 'rm -rf "$S" /root/reposync.secrets /home/user/box-export.py' EXIT
umask 077
cp_if(){ [ -e "$1" ] && { mkdir -p "$S/$(dirname "$2")"; cp -a "$1" "$S/$2"; } || true; }

# --- compose stacks (+ env as key-only examples) ---
for st in core plex tdarr ops livetv glances; do
  for f in compose.yaml compose.nodata.yaml; do cp_if /opt/media/stacks/$st/$f stacks/$st/$f; done
  for envf in /opt/media/stacks/$st/.env /opt/media/stacks/$st/*.env; do
    [ -f "$envf" ] || continue
    out="stacks/$st/$(basename "$envf" | sed 's/^\.env$/env/').example"; mkdir -p "$S/stacks/$st"
    awk -F= '/^[[:space:]]*#/||NF<2{print;next} $1~/^(PUID|PGID|TZ|RENDER_GID|COMPOSE_FILE|UMASK)$/{print;next} {print $1"=<secret: set on the box>"}' "$envf" > "$S/$out"
  done
done
cp_if /opt/media/dockge/compose.yaml dockge/compose.yaml

# --- host scripts (text only) ---
for f in media-config-backup migrate-round1-guard migrate-round1-v2 migrate-round2 migration-status tdarr-status tdarr-pilot-copy tdarr-pilot-report tdarr-swap selftest-status host-health-push mount-push safekeep-copy spin-test usb-watchdog snapraid-nightly ha-ws; do
  [ -f /usr/local/sbin/$f ] || continue
  ext=.sh; head -1 /usr/local/sbin/$f | grep -q python && ext=.py
  cp_if /usr/local/sbin/$f scripts-reference/$f$ext
done

# --- systemd units ---
for u in media-config-backup.service media-config-backup.timer migration-status.service migration-status.timer \
         tdarr-status.service tdarr-status.timer tdarr-swap.service tdarr-swap.timer selftest-status.service selftest-status.timer host-health-push.service host-health-push.timer \
         mount-push.service mount-push.timer usb-watchdog.service wifi-powersave-off.service \
         snapraid-nightly.service snapraid-nightly.timer; do cp_if /etc/systemd/system/$u systemd/$u; done
for f in /etc/systemd/system/docker.service.d/*.conf; do cp_if "$f" "systemd/docker.service.d/$(basename "$f")"; done
for f in /etc/systemd/system/systemd-networkd-wait-online.service.d/*.conf; do cp_if "$f" "systemd/systemd-networkd-wait-online.service.d/$(basename "$f")"; done

# --- host config ---
cp_if /etc/fstab host/fstab
cp_if /etc/snapraid.conf host/snapraid.conf
cp_if /etc/media-server/migration-rounds.json host/migration-rounds.json
cp_if /etc/mdadm/mdadm.conf host/mdadm.conf
cp_if /etc/docker/daemon.json host/docker-daemon.json
for f in /etc/sysctl.d/99-*.conf; do cp_if "$f" "host/sysctl.d/$(basename "$f")"; done
if command -v virsh >/dev/null && virsh -c qemu:///system dominfo haos >/dev/null 2>&1; then mkdir -p "$S/host/libvirt"; virsh -c qemu:///system dumpxml --inactive --security-info haos | sed -E "/<uuid>|<nvram|<source file=.*nvram/d" > "$S/host/libvirt/haos.xml"; fi
if command -v tailscale >/dev/null; then mkdir -p "$S/host"; tailscale debug prefs 2>/dev/null | python3 -c 'import json,sys; p=json.load(sys.stdin); print(json.dumps({k: p.get(k) for k in ("AdvertiseRoutes","RouteAll","ExitNodeID","AdvertiseTags","RunSSH","ShieldsUp","Hostname","CorpDNS")}, indent=1, sort_keys=True))' > "$S/host/tailscale-prefs.json" || true; fi
if [ -f /etc/netplan/01-media-server.yaml ]; then
  mkdir -p "$S/host"; sed -E 's/^([[:space:]]*password:).*/\1 <REDACTED>/' /etc/netplan/01-media-server.yaml > "$S/host/netplan-01-media-server.yaml"
fi

# --- app config files that are plain text and secret-free (or redacted) ---
for f in services.yaml settings.yaml widgets.yaml docker.yaml bookmarks.yaml custom.css custom.js; do cp_if /opt/media/config/homepage/$f config/homepage/$f; done
cp_if /opt/media/config/filebrowser/config.yaml config/filebrowser/config.yaml
# PrismCast: channel/provider settings only (no logins; Chrome profile + health.json stay on the box)
for f in config.json provider-lineups.json; do cp_if /opt/media/config/prismcast/$f config/prismcast/$f; done
for f in /opt/media/config/recyclarr/configs/*.yml; do cp_if "$f" "config/recyclarr/configs/$(basename "$f")"; done
cp_if /opt/media/config/recyclarr/settings.yml config/recyclarr/settings.yml
for k in config.yml config.yml.pending; do
  [ -f /opt/media/config/kometa/$k ] || continue
  mkdir -p "$S/config/kometa"
  sed -E 's/^([[:space:]]*(token|apikey|api_key|client_secret|password):).*/\1 <REDACTED>/' /opt/media/config/kometa/$k > "$S/config/kometa/$k"
done

# --- generated inventory (stable fields only, so it doesn't churn every sync) ---
{
  echo "# Live inventory (generated by tools/sync-from-box.sh; do not edit)"
  echo; echo "## Containers"; echo; echo '```'
  docker ps -a --format '{{.Names}}\t{{.Image}}\t{{.State}}' | sort | column -t -s $'\t'
  echo '```'; echo; echo "## Timers"; echo; echo '```'
  systemctl list-unit-files --type=timer --state=enabled --no-legend | awk '{print $1}' | grep -E 'media|migration|mount-push|snapraid' | sort
  echo '```'; echo; echo "## Mounts (fstab-managed media/scratch)"; echo; echo '```'
  findmnt -rno TARGET,FSTYPE,OPTIONS | awk '$1 ~ /^\/(data|scratch|mnt\/(disk|parity|mig))/ {print $1, $2, ($3 ~ /(^|,)ro(,|$)/ ? "ro" : "rw")}' | sort
  echo '```'; echo; echo "## Host packages"; echo; echo '```'
  for p in docker-ce docker-compose-plugin tailscale mergerfs snapraid smartmontools; do
    v=$(dpkg-query -W -f='${Version}' $p 2>/dev/null || true); echo "$p ${v:-not installed}"
  done
  echo '```'
} > "$S/INVENTORY.md"

# --- secret VALUE scan ---
: > /root/reposync.secrets
for envf in /opt/media/stacks/*/.env /opt/media/stacks/*/*.env /opt/media/dockge/.env; do
  [ -f "$envf" ] && awk -F= '!/^#/ && NF>1 && $1!~/^(PUID|PGID|TZ|RENDER_GID|COMPOSE_FILE|UMASK|WUD_AUTH_ADMIN_USER|HOMEPAGE_VAR_WUD_USER)$/ {sub(/^[^=]*=/,""); print}' "$envf" >> /root/reposync.secrets
done
cat /etc/media-server/* 2>/dev/null | grep -oE '[A-Za-z0-9_-]{12,}' >> /root/reposync.secrets || true
for x in sonarr radarr prowlarr; do grep -oP '(?<=<ApiKey>)[^<]+' /opt/media/config/$x/config.xml 2>/dev/null >> /root/reposync.secrets || true; done
grep -E '^(api_key|nzb_key) *=' /opt/media/config/sabnzbd/sabnzbd.ini 2>/dev/null | sed -E 's/^[^=]*= *//' >> /root/reposync.secrets || true
grep -oE '(token|apikey|api_key): *[^ ]+' /opt/media/config/kometa/config.yml* 2>/dev/null | sed -E 's/^[^:]*:[^:]*: *//' >> /root/reposync.secrets || true
grep -E '^[[:space:]]*[a-z_]+: ' /opt/media/config/recyclarr/secrets.yml 2>/dev/null | sed -E 's/^[^:]*: *//' >> /root/reposync.secrets || true
cat /opt/media/config/kometa/.tmdb_key 2>/dev/null >> /root/reposync.secrets || true
grep -E '^[[:space:]]*password:' /etc/netplan/*.yaml 2>/dev/null | sed -E 's/^[^:]*:[^:]*: *//; s/^"//; s/"$//' >> /root/reposync.secrets || true
# DB/API-held settings (Kuma, Tdarr, *arr, Plex, ...): exported redacted; redacted values join the scan list
if [ -f /home/user/box-export.py ]; then
  python3 /home/user/box-export.py "$S/exports" /root/reposync.secrets
  rm -f /home/user/box-export.py
fi
sed -i -E 's/^"//; s/"$//; /^.{0,7}$/d; /^<.*>$/d' /root/reposync.secrets
sort -u -o /root/reposync.secrets /root/reposync.secrets
echo "secret values checked: $(wc -l < /root/reposync.secrets)"
hits=$(grep -rlF -f /root/reposync.secrets "$S" || true)
if [ -n "$hits" ]; then echo "ABORT: secret value found in: ${hits//$S\//}"; exit 1; fi
echo "secret scan: clean"
tar -C "$S" -czf /root/reposync.tgz . && chown user:user /root/reposync.tgz 2>/dev/null; mv /root/reposync.tgz /home/user/reposync.tgz
chmod 600 /home/user/reposync.tgz; chown user:user /home/user/reposync.tgz
echo "files staged: $(find "$S" -type f | wc -l)"
